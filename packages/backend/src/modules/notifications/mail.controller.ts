import { Body, Controller, Get, Post, Put, Query, UseGuards } from "@nestjs/common";
import {
  adminMailSendSchema,
  mailSettingsInputSchema,
  mailTestSchema,
  UserRole,
} from "@advo/contracts";
import { CurrentUser, Roles, RolesGuard, SessionAuthGuard, type RequestActor } from "../../common/guards/session.guard.js";
import { parse } from "../../common/http.js";
import { enforceRateLimit } from "../../common/rate-limit.js";
import {
  listMailMessages,
  listMailRecipients,
  mailSettingsOverview,
  saveMailSettings,
  sendAdminMail,
  sendTestMail,
} from "./mail.service.js";

/**
 * Admin → Mail. One screen owns the transport, the delivery log and the
 * hand-composed security/info mail.
 *
 * OTP mail is never sent from here: it is generated by the auth service so the
 * code never crosses the Admin API, and the log only records a code-free
 * preview.
 */
@Controller("admin/mail")
@UseGuards(SessionAuthGuard, RolesGuard)
@Roles(UserRole.ADMIN)
export class MailController {
  @Get()
  overview() {
    return mailSettingsOverview();
  }

  @Put("settings")
  async settings(@CurrentUser() actor: RequestActor, @Body() body: unknown) {
    await saveMailSettings(actor.id, parse(mailSettingsInputSchema, body));
    return mailSettingsOverview();
  }

  @Post("test")
  async test(@CurrentUser() actor: RequestActor, @Body() body: unknown) {
    await enforceRateLimit("mail-test", actor.id, 10, 900);
    return sendTestMail(actor.id, parse(mailTestSchema, body).to);
  }

  @Post("send")
  async send(@CurrentUser() actor: RequestActor, @Body() body: unknown) {
    await enforceRateLimit("mail-send", actor.id, 20, 3600);
    return sendAdminMail(actor.id, parse(adminMailSendSchema, body));
  }

  @Get("messages")
  messages(@Query("state") state?: string, @Query("q") q?: string, @Query("take") take?: string) {
    const parsed = take ? Number(take) : undefined;
    return listMailMessages({
      state,
      q,
      take: Number.isFinite(parsed) && parsed && parsed > 0 ? Math.min(Math.floor(parsed), 250) : undefined,
    });
  }

  @Get("recipients")
  recipients() {
    return listMailRecipients();
  }
}
